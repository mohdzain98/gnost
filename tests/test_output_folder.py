"""The GNOST folder: where `onboard` and `analyze` write, and how `open` finds it."""

from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path
from typing import List

from typing import Callable

import pytest

import gnost.cli.app as app
from gnost.cli.commands.onboard import run
from gnost.config.settings import ConfigError, GnostConfig, _validate
from gnost.utils.layout import OutputLayout


def _main(monkeypatch: pytest.MonkeyPatch, *argv: str) -> int:
    monkeypatch.setattr("sys.argv", ["gnost", *argv])
    return app.main()


def test_onboard_writes_everything_into_the_gnost_folder(
    fixture_repo: Callable[[str], Path],
) -> None:
    root = fixture_repo("python_app")
    run(path=str(root))
    folder = root / ".gnost"
    for name in ("README.md", ".gitignore", "ONBOARD.md", "insights.json", "flow.html"):
        assert (folder / name).is_file(), name
    assert (folder / "flow" / "FLOW-full.mmd").is_file()
    assert json.loads((folder / "insights.json").read_text())["schema_version"]
    # Nothing is written to the old places.
    assert not (root / "ONBOARD.md").exists()
    assert not (root / "docs").exists()


def test_the_folder_readme_explains_itself(fixture_repo: Callable[[str], Path]) -> None:
    root = fixture_repo("python_app")
    run(path=str(root))
    text = (root / ".gnost" / "README.md").read_text(encoding="utf-8")
    assert "generated by [GNOST]" in text and "gnost onboard" in text


def test_no_html_skips_the_page_and_mermaid_only_writes_one_diagram(
    fixture_repo: Callable[[str], Path],
) -> None:
    root = fixture_repo("python_app")
    run(path=str(root), html=False)
    assert not (root / ".gnost" / "flow.html").exists()
    assert (root / ".gnost" / "ONBOARD.md").exists()

    other = fixture_repo("js_app")
    run(path=str(other), diagram_only=True)
    assert (other / ".gnost" / "flow" / "FLOW-full.mmd").exists()
    assert not (other / ".gnost" / "ONBOARD.md").exists()
    assert not (other / ".gnost" / "insights.json").exists()


def test_html_is_ignored_but_markdown_and_json_can_be_committed(
    fixture_repo: Callable[[str], Path],
) -> None:
    root = fixture_repo("python_app")
    subprocess.run(["git", "init", "-q"], cwd=root, check=True)
    run(path=str(root))

    def ignored(rel: str) -> bool:
        return (
            subprocess.run(["git", "check-ignore", "-q", rel], cwd=root).returncode == 0
        )

    assert ignored(".gnost/flow.html")
    for rel in (
        ".gnost/ONBOARD.md",
        ".gnost/insights.json",
        ".gnost/README.md",
        ".gnost/flow/FLOW-full.mmd",
        ".gnost/flow/FLOW-full.md",
    ):
        assert not ignored(rel), rel


def test_a_second_run_does_not_scan_the_output_of_the_first(
    fixture_repo: Callable[[str], Path],
) -> None:
    root = fixture_repo("python_app")
    (root / ".gnost").mkdir()
    (root / ".gnost" / "generated.py").write_text("x = 1\n")
    (root / "docs" / "flow").mkdir(parents=True)
    (root / "docs" / "flow" / "old.py").write_text("y = 2\n")
    run(path=str(root))
    files = json.loads((root / ".gnost" / "insights.json").read_text())
    text = json.dumps(files)
    assert "generated.py" not in text and "old.py" not in text


def test_output_dir_setting_chooses_the_folder(
    fixture_repo: Callable[[str], Path],
) -> None:
    root = fixture_repo("python_app")
    (root / ".gnost.toml").write_text('output_dir = "reports/gnost"\n')
    assert _main_in(root, "onboard", ".") == 0
    assert (root / "reports" / "gnost" / "ONBOARD.md").is_file()
    assert not (root / ".gnost").exists()


def _main_in(root: Path, *argv: str) -> int:
    import os

    old = os.getcwd()
    os.chdir(root)
    try:
        import sys

        sys.argv = ["gnost", *argv]
        return app.main()
    finally:
        os.chdir(old)


@pytest.mark.parametrize("bad", ["", "  ", "../outside", "a/../../b"])
def test_output_dir_must_stay_inside_the_project(bad: object) -> None:
    with pytest.raises(ConfigError):
        _validate({"output_dir": bad}, GnostConfig())



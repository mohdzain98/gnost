def test_the_moved_notice_appears_once_when_old_output_exists(
    fixture_repo: Callable[[str], Path], capsys: pytest.CaptureFixture[str]
) -> None:
    root = fixture_repo("python_app")
    (root / "ONBOARD.md").write_text("old guide\n")
    run(path=str(root))
    assert "now writes to .gnost/" in capsys.readouterr().out
    assert (root / "ONBOARD.md").read_text() == "old guide\n"  # never touched
    run(path=str(root))
    assert "now writes to .gnost/" not in capsys.readouterr().out


def test_open_flow_uses_the_saved_page_and_falls_back_to_old_output(
    fixture_repo: Callable[[str], Path],
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
) -> None:
    root = fixture_repo("python_app")
    opened: List[str] = []
    monkeypatch.setattr("webbrowser.open", lambda url: opened.append(url) or True)
    monkeypatch.chdir(root)
    assert _main(monkeypatch, "open", "flow") == 1  # nothing yet

    # Old layout only: found, with a notice about the move.
    old = root / "docs" / "flow"
    old.mkdir(parents=True)
    (old / "flow-complete.mmd").write_text("flowchart TD\n  a --> b\n")
    assert _main(monkeypatch, "open", "flow") == 0 and opened
    assert "now writes to .gnost/" in capsys.readouterr().err

    # New layout: the saved page is opened as it is.
    opened.clear()
    shutil.rmtree(root / "docs")
    run(path=str(root))
    assert _main(monkeypatch, "open", "flow") == 0
    assert opened and opened[0].endswith("/.gnost/flow.html")


def test_open_report_reads_the_new_and_the_old_location(
    fixture_repo, monkeypatch, capsys
):
    root = fixture_repo("python_app")
    opened: List[str] = []
    monkeypatch.setattr("webbrowser.open", lambda url: opened.append(url) or True)
    monkeypatch.chdir(root)
    assert _main(monkeypatch, "open", "report") == 1

    old = root / "docs" / "analysis"
    old.mkdir(parents=True)
    (old / "gnost_analysis.html").write_text("<html></html>")
    assert _main(monkeypatch, "open", "report") == 0
    assert "now writes to .gnost/" in capsys.readouterr().err

    layout = OutputLayout(str(root))
    Path(layout.analysis_dir).mkdir(parents=True)
    Path(layout.analysis_html).write_text("<html></html>")
    opened.clear()
    assert _main(monkeypatch, "open", "report") == 0
    assert opened[0].endswith("/.gnost/analysis/analysis.html")


def test_generated_markdown_ends_with_the_footer_and_it_can_be_switched_off(
    tmp_path, fixture_repo
) -> None:
    from gnost import __version__
    from gnost.cli.commands.onboard import run

    root = fixture_repo("python_app")
    run(path=str(root))
    for name in ("ONBOARD.md", "flow/entry-paths.md", "flow/FLOW-full.md"):
        text = (root / ".gnost" / name).read_text(encoding="utf-8")
        assert (
            f"Generated by [GNOST](https://gnost.readthedocs.io) {__version__}" in text
        )
        assert text.rstrip().endswith("`</sub>")
    run(path=str(root), footer=False)
    assert "Generated by [GNOST]" not in (root / ".gnost" / "ONBOARD.md").read_text(
        encoding="utf-8"
    )


def test_the_footer_class_is_empty_when_disabled() -> None:
    from gnost.utils.footer import Footer

    assert Footer(False).line() == "" and Footer(False).append("x\n") == "x\n"
    assert (
        Footer(True, "9.9.9")
        .append("x\n")
        .endswith("9.9.9. Try it on your own code: `npx gnost-cli onboard .`</sub>\n")
    )


def test_the_footer_command_fits_the_main_language() -> None:
    from gnost.utils.footer import Footer

    base = Footer(True, "1.0")
    assert (
        "uvx gnost onboard ."
        in base.for_languages({"python": 30, "javascript": 2}).line()
    )
    assert (
        "mvn io.github.mohdzain98:gnost-maven-plugin:onboard"
        in base.for_languages({"java": 12}).line()
    )
    assert (
        "npx gnost-cli onboard ."
        in base.for_languages({"typescript": 9, "python": 1}).line()
    )
    assert base.for_languages({}).line() == base.line()  # unknown: the default
    assert base.for_languages({"rust": 5}).line() == base.line()
    assert Footer(False).for_languages({"java": 3}).line() == ""

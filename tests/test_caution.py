import json
from pathlib import Path

import pytest

from gnost.core.caution import (
    DEFERRED_CYCLE_STRENGTH,
    CautionSettings,
    FileMetrics,
    is_generated,
    normalize,
    rank_files,
    score_file,
    _python_measures,
)
from gnost.core.cycles import find_cycles
from gnost.core.graph import DependencyGraph
from gnost.languages.java import JavaAdapter
from gnost.languages.javascript import JavaScriptAdapter
from gnost.languages.python import PythonAdapter
from gnost.languages.typescript import TypeScriptAdapter
from gnost.scanner.engine import ScannerEngine

S = CautionSettings()


def metrics(**kw) -> FileMetrics:
    base = dict(
        path="/p/a.py",
        language="python",
        loc=50,
        fan_in=0,
        fan_out=0,
        complexity=3.0,
        silent_handlers=0,
    )
    base.update(kw)
    return FileMetrics(**base)


# ---- scoring rules ----


def test_normalize_is_linear_and_clamped():
    assert normalize(5, 10, 30) == 0
    assert normalize(20, 10, 30) == 0.5
    assert normalize(99, 10, 30) == 1
    assert normalize(1, 5, 5) == 0 and normalize(5, 5, 5) == 1


def test_quiet_file_scores_zero():
    scored = score_file(metrics(), S)
    assert scored.score == 0 and scored.level == "low" and scored.factors == []


def test_one_strong_signal_is_enough_to_flag_a_file():
    scored = score_file(metrics(fan_in=40), S)
    assert scored.score == 80 and scored.level == "high"
    assert [f.name for f in scored.factors] == ["impact"]


def test_moderate_signals_compound():
    one = score_file(metrics(loc=600), S).score
    two = score_file(metrics(loc=600, fan_in=17), S).score
    assert 0 < one < two < 100
    assert two > S.threshold > one


def test_import_time_cycle_outweighs_deferred_cycle():
    eager = score_file(metrics(cycle="import-time"), S)
    lazy = score_file(metrics(cycle="deferred"), S)
    assert eager.score == 90
    assert lazy.score == round(100 * 0.9 * DEFERRED_CYCLE_STRENGTH, 1)
    assert eager.factors[0].name == "cycles"


def test_unmeasurable_signals_make_a_score_partial_not_lower():
    py = score_file(metrics(loc=1000), S)
    other = score_file(
        metrics(language="java", loc=1000, complexity=None, silent_handlers=None), S
    )
    assert py.score == other.score and not py.partial and other.partial


def test_estimated_complexity_uses_its_own_range_and_is_flagged():
    scored = score_file(
        metrics(
            language="typescript",
            complexity=250,
            complexity_estimated=True,
            silent_handlers=None,
        ),
        S,
    )
    (factor,) = scored.factors
    assert factor.name == "complexity" and factor.estimated and factor.strength == 1


def test_settings_change_weights_and_ranges():
    custom = CautionSettings(
        weights={**S.weights, "size": 1.0}, ranges={**S.ranges, "size": (10, 20)}
    )
    assert score_file(metrics(loc=20), custom).score == 100
    assert score_file(metrics(loc=20), S).score == 0


def test_severity_follows_score():
    severities = [score_file(metrics(fan_in=n), S).severity for n in (4, 12, 17, 30)]
    assert severities == [1, 2, 2, 4]  # scores 0, 25, 40, 80
    assert score_file(metrics(cycle="import-time"), S).severity == 5


# ---- measuring Python ----


def test_python_measures_complexity_and_silent_handlers():
    src = (
        "import logging\n"
        "def busy(a, b):\n"
        "    if a:\n        return 1\n"
        "    for x in b:\n        if x and a:\n            return 2\n"
        "    return 0\n"
        "def swallow():\n"
        "    try:\n        run()\n    except Exception:\n        pass\n"
        "    try:\n        run()\n    except ValueError:\n        logging.warning('x')\n"
        "    try:\n        run()\n    except KeyError:\n        raise\n"
        "    try:\n        run()\n    except OSError:\n        value = None\n"
    )
    complexity, silent = _python_measures(src)
    assert complexity >= 5
    assert (
        silent == 2
    )  # `pass` and `value = None`; the logged and re-raised ones are fine


def test_python_measures_syntax_error_returns_none():
    assert _python_measures("def broken(:\n") == (None, None)


# ---- generated code ----


def test_generated_files_are_recognised():
    assert is_generated("/p/src/generated/types.ts", "export {};")
    assert is_generated("/p/x.py", "# Code generated by protoc. DO NOT EDIT.\nx = 1\n")
    assert is_generated("/p/y.ts", "// @generated\nexport {};\n")
    assert not is_generated("/p/z.py", "x = 1\n")


# ---- ranking on real scans ----


def scan(root: Path):
    engine = ScannerEngine(
        [PythonAdapter(), JavaScriptAdapter(), TypeScriptAdapter(), JavaAdapter()]
    )
    result = engine.scan(str(root))
    graph = DependencyGraph.from_scan(result)
    return result, graph, find_cycles(graph)


def test_rank_flags_the_files_in_an_import_time_cycle(fixture_repo):
    result, graph, cycles = scan(fixture_repo("cyclic_py"))
    top = rank_files(result, graph, cycles)[:2]
    assert {Path(s.path).name for s in top} == {"a.py", "b.py"}
    assert all(s.factors[0].name == "cycles" for s in top)


def test_rank_skips_generated_files(tmp_path):
    (tmp_path / "gen").mkdir()
    (tmp_path / "gen" / "generated").mkdir()
    big = "\n".join(f"x{i} = {i}" for i in range(1500))
    (tmp_path / "gen" / "generated" / "big.py").write_text(big)
    (tmp_path / "hand.py").write_text(big)
    result, graph, cycles = scan(tmp_path)
    names = [Path(s.path).name for s in rank_files(result, graph, cycles)]
    assert names == ["hand.py"]


def test_high_fan_in_and_large_files_end_up_in_caution_areas(tmp_path):
    from gnost.core.flow import FlowBuilder
    from gnost.core.insight_builder import InsightBuilder

    (tmp_path / "core.py").write_text("X = 1\n")
    (tmp_path / "huge.py").write_text("\n".join(f"v{i} = {i}" for i in range(1400)))
    for i in range(30):
        (tmp_path / f"user{i}.py").write_text("import core\n")
    (tmp_path / "main.py").write_text(
        'import core\nif __name__ == "__main__":\n    pass\n'
    )
    result, graph, _ = scan(tmp_path)
    flow = FlowBuilder(graph, result).build()
    areas = InsightBuilder(result, flow, graph).build().caution_areas

    by_name = {Path(a.path).name: a for a in areas}
    assert by_name["core.py"].category.value == "high_impact"
    assert "Imported by 31 files" in by_name["core.py"].description
    assert by_name["huge.py"].category.value == "large_file"
    assert "1,400 lines of code" in by_name["huge.py"].description
    assert [a.score for a in areas] == sorted((a.score for a in areas), reverse=True)


def test_threshold_and_limit_apply(tmp_path):
    from gnost.core.flow import FlowBuilder
    from gnost.core.insight_builder import InsightBuilder

    for i in range(5):
        (tmp_path / f"f{i}.py").write_text("\n".join(f"v{j} = 1" for j in range(1200)))
    result, graph, _ = scan(tmp_path)
    flow = FlowBuilder(graph, result).build()
    build = lambda s: InsightBuilder(result, flow, graph, s).build().caution_areas  # noqa: E731
    assert len(build(CautionSettings(limit=2))) == 2
    assert build(CautionSettings(threshold=99)) == []



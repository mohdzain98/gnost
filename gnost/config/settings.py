"""`.gnost.toml`: per-project settings.

Looked up from the scanned folder upwards (it stops at the repository root), so a
file at the root of a repo applies to every command run inside it. Precedence is
command-line flags, then this file, then built-in defaults. Unknown keys are
reported as warnings; wrong value types are errors that name the key.

Example::

    exclude = ["legacy", "*.generated.ts"]      # skipped by onboard and analyze
    output_dir = ".gnost"                       # where GNOST writes its files
    check_updates = true                        # say so when a newer gnost exists
    footer = true                               # "Generated by GNOST" in the Markdown files

    [onboard]
    max_edges = 150          # largest diagram drawn file by file
    collapse = 1             # always group diagrams by folder
    pages = true             # also publish the explorer for GitHub Pages (or a folder: "docs/gnost")
    depth = 3                # limit flow depth

    [caution]                # which files are "risky to change"
    threshold = 50           # lowest score reported (0-100)
    limit = 15               # most files reported
    [caution.weights]        # most a signal can add to a score (0-1)
    size = 0.5
    [caution.ranges]         # [counts as 0, counts as 1]
    size = [300, 1500]

    [risk]                   # files that are fragile AND changing (needs git)
    threshold = 20           # lowest risk listed, 0-100
    limit = 10               # most files listed

    [history]                # how change hotspots are measured (needs git)
    days = 365               # how far back to look
    exclude_authors = ["*[bot]"]

    [analyze]
    analyzers = ["maintainability", "readability"]
    fail_under = 7.5         # CI: exit 3 when the final score (0-10) is lower
    score = "density"        # or "average": the 0.7 formula, kept for one release
    badge = true             # write .gnost/badge.svg for the README (or a path)
    timeout = 600
    max_findings = 500
    parallel = true
"""

from __future__ import annotations

import os
import sys
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional

from gnost.utils.layout import DEFAULT_OUTPUT_DIR
from gnost.core.architecture import ArchitectureSettings, ForbiddenImportRule
from gnost.core.risk import RiskSettings
from gnost.vcs.history import HistorySettings
from gnost.core.caution import (
    DEFAULT_RANGES,
    DEFAULT_WEIGHTS,
    CautionSettings,
)

try:
    import tomllib  # Python 3.11+
except ModuleNotFoundError:  # pragma: no cover
    import tomli as tomllib  # type: ignore[no-redef]

CONFIG_NAME = ".gnost.toml"

# Built-in `analyze` defaults (also what `gnost init` writes).
ANALYZE_TIMEOUT = 900
ANALYZE_MAX_FINDINGS = 1000


class ConfigError(Exception):
    """The config file cannot be used; the message names the file and key."""


_NUMBER = (int, float)
_SWITCH_OR_TEXT = (bool, str)
# section -> key -> accepted type(s); `None` section is the top level
SCHEMA: Dict[Optional[str], Dict[str, Any]] = {
    None: {
        "exclude": list,
        "output_dir": str,
        "check_updates": bool,
        "footer": bool,
    },
    "onboard": {
        "max_edges": int,
        "collapse": int,
        "depth": int,
        "pages": _SWITCH_OR_TEXT,
    },
    "caution": {"threshold": _NUMBER, "limit": int},
    "risk": {"threshold": _NUMBER, "limit": int, "churn_weight": _NUMBER},
    "history": {
        "enabled": bool,
        "days": int,
        "max_commits": int,
        "recent_days": int,
        "exclude_authors": list,
        "max_files_per_commit": int,
        "min_commits": int,
        "top": int,
    },
    "analyze": {
        "analyzers": list,
        "languages": list,
        "timeout": int,
        "max_findings": int,
        "parallel": bool,
        "fail_under": _NUMBER,
        "baseline": str,
        "score": str,
        "badge": _SWITCH_OR_TEXT,
    },
    "architecture": {"layers": list, "rules": list, "fail": bool},
}
_TABLES = {"caution.weights", "caution.ranges"}


@dataclass
class GnostConfig:
    path: Optional[str] = None
    values: Dict[str, Any] = field(default_factory=dict)
    warnings: List[str] = field(default_factory=list)

    def get(self, section: Optional[str], key: str, default: Any = None) -> Any:
        scope = self.values if section is None else self.values.get(section, {})
        return scope.get(key, default)

    @property
    def exclude(self) -> List[str]:
        return list(self.get(None, "exclude", []))

    @property
    def check_updates(self) -> bool:
        """Whether `gnost --version` may look for a newer release."""
        return bool(self.get(None, "check_updates", True))

    @property
    def footer(self) -> bool:
        """Whether generated Markdown files end with the "Generated by GNOST" line."""
        return bool(self.get(None, "footer", True))

    @property
    def output_dir(self) -> str:
        """The folder GNOST writes to, relative to the project root (default .gnost)."""
        return str(self.get(None, "output_dir", DEFAULT_OUTPUT_DIR))

    def pick(self, section: str, key: str, cli_value: Any, default: Any) -> Any:
        """CLI flag, else config file, else default."""
        if cli_value is not None:
            return cli_value
        return self.get(section, key, default)

    def risk_settings(self) -> RiskSettings:
        """Risk settings: the [risk] table over the defaults."""
        base = RiskSettings()
        given = self.values.get("risk", {})
        return RiskSettings(
            threshold=float(given.get("threshold", base.threshold)),
            limit=int(given.get("limit", base.limit)),
            churn_weight=float(given.get("churn_weight", base.churn_weight)),
        )

    def history_settings(self) -> HistorySettings:
        """Change-history settings: the [history] table over the defaults."""
        base = HistorySettings()
        given = self.values.get("history", {})
        return HistorySettings(
            enabled=bool(given.get("enabled", base.enabled)),
            days=int(given.get("days", base.days)),
            max_commits=int(given.get("max_commits", base.max_commits)),
            recent_days=int(given.get("recent_days", base.recent_days)),
            exclude_authors=tuple(given.get("exclude_authors", base.exclude_authors)),
            max_files_per_commit=int(
                given.get("max_files_per_commit", base.max_files_per_commit)
            ),
            min_commits=int(given.get("min_commits", base.min_commits)),
            top=int(given.get("top", base.top)),
        )

    def architecture_settings(self) -> ArchitectureSettings:
        """The [architecture] table as rule objects (empty when there is none)."""
        given = self.values.get("architecture", {})
        rules = []
        for index, item in enumerate(given.get("rules", []), start=1):
            sources = item["from"] if isinstance(item["from"], list) else [item["from"]]
            rules.append(
                ForbiddenImportRule(
                    name=item.get("name") or f"rule {index}",
                    sources=tuple(sources),
                    forbidden=tuple(item["must_not_import"]),
                    allow=tuple(item.get("allow", [])),
                )
            )
        return ArchitectureSettings(
            forbidden=tuple(rules),
            layers=tuple(given.get("layers", [])),
            fail=bool(given.get("fail", False)),
        )

    def caution_settings(self) -> CautionSettings:
        weights = dict(DEFAULT_WEIGHTS)
        weights.update(self.values.get("caution", {}).get("weights", {}))
        ranges = dict(DEFAULT_RANGES)
        for name, pair in self.values.get("caution", {}).get("ranges", {}).items():
            ranges[name] = (float(pair[0]), float(pair[1]))
        caution = self.values.get("caution", {})
        base = CautionSettings()
        return CautionSettings(
            weights=weights,
            ranges=ranges,
            threshold=float(caution.get("threshold", base.threshold)),
            limit=int(caution.get("limit", base.limit)),
        )


def find_config(start: str) -> Optional[str]:
    """The nearest `.gnost.toml` from `start` upwards, not past the repo root."""
    current = os.path.abspath(start)
    if os.path.isfile(current):
        current = os.path.dirname(current)
    while True:
        candidate = os.path.join(current, CONFIG_NAME)
        if os.path.isfile(candidate):
            return candidate
        if os.path.isdir(os.path.join(current, ".git")):
            return None
        parent = os.path.dirname(current)
        if parent == current:
            return None
        current = parent


def load_config(start: str = ".") -> GnostConfig:
    """Load and validate the config that applies to `start` (empty if none)."""
    path = find_config(start)
    if path is None:
        return GnostConfig()
    try:
        with open(path, "rb") as f:
            raw = tomllib.load(f)
    except tomllib.TOMLDecodeError as exc:
        raise ConfigError(f"{path}: not valid TOML ({exc})") from exc
    except OSError as exc:
        raise ConfigError(f"{path}: cannot be read ({exc})") from exc

    config = GnostConfig(path=path)
    _validate(raw, config)
    return config


def _type_name(expected: Any) -> str:
    if expected is _NUMBER:
        return "a number"
    if expected is _SWITCH_OR_TEXT:
        return "true, false or a folder name"
    return {
        list: "a list",
        int: "an integer",
        bool: "true or false",
        str: "text",
    }[expected]


def _is(value: Any, expected: Any) -> bool:
    if expected is int:
        return isinstance(value, int) and not isinstance(value, bool)
    if expected is _NUMBER:
        return isinstance(value, _NUMBER) and not isinstance(value, bool)
    return isinstance(value, expected)


def _validate(raw: Dict[str, Any], config: GnostConfig) -> None:
    where = config.path or CONFIG_NAME
    values: Dict[str, Any] = {}

    for key, value in raw.items():
        if key in SCHEMA[None]:
            _check(where, key, value, SCHEMA[None][key])
            values[key] = value
        elif key in SCHEMA and isinstance(value, dict):
            values[key] = _validate_section(where, key, value, config)
        else:
            config.warnings.append(f"{where}: unknown setting '{key}' (ignored)")

    exclude = values.get("exclude", [])
    if not all(isinstance(p, str) for p in exclude):
        raise ConfigError(f"{where}: 'exclude' must be a list of strings")
    if "output_dir" in values:
        out = values["output_dir"].strip()
        parts = out.replace("\\", "/").split("/")
        if not out or ".." in parts:
            raise ConfigError(
                f"{where}: 'output_dir' must be a folder name or path inside the "
                "project, without '..'"
            )
        values["output_dir"] = out
    config.values = values


def _validate_section(
    where: str, section: str, raw: Dict[str, Any], config: GnostConfig
) -> Dict[str, Any]:
    allowed = SCHEMA[section]
    out: Dict[str, Any] = {}
    for key, value in raw.items():
        dotted = f"{section}.{key}"
        if key in allowed:
            _check(where, dotted, value, allowed[key])
            out[key] = value
        elif dotted in _TABLES and isinstance(value, dict):
            out[key] = _validate_table(where, dotted, value, config)
        else:
            config.warnings.append(f"{where}: unknown setting '{dotted}' (ignored)")

    if section == "analyze" and "languages" in out:
        from gnost.analysis.languages import AnalysisLanguages

        unknown = [
            n
            for n in out["languages"]
            if str(n).lower() not in AnalysisLanguages.names()
        ]
        if unknown:
            raise ConfigError(
                f"{where}: 'analyze.languages' has unknown {', '.join(map(str, unknown))}; "
                f"choose from {', '.join(AnalysisLanguages.names())}"
            )

    if section == "architecture":
        _validate_architecture(where, out, config)

    if section == "risk":
        if "limit" in out and out["limit"] < 1:
            raise ConfigError(f"{where}: 'risk.limit' must be 1 or more")
        for key in ("threshold", "churn_weight"):
            low, high = (0, 100) if key == "threshold" else (0, 1)
            if key in out and not low <= out[key] <= high:
                raise ConfigError(
                    f"{where}: 'risk.{key}' must be between {low} and {high}"
                )
    if section == "history":
        for key in (
            "days",
            "max_commits",
            "recent_days",
            "max_files_per_commit",
            "min_commits",
            "top",
        ):
            if key in out and out[key] < 1:
                raise ConfigError(f"{where}: 'history.{key}' must be 1 or more")
        if "exclude_authors" in out and not all(
            isinstance(a, str) for a in out["exclude_authors"]
        ):
            raise ConfigError(
                f"{where}: 'history.exclude_authors' must be a list of strings"
            )
    if (
        section == "analyze"
        and "fail_under" in out
        and not 0 <= out["fail_under"] <= 10
    ):
        raise ConfigError(f"{where}: 'analyze.fail_under' must be between 0 and 10")
    if section == "analyze" and out.get("score", "density") not in (
        "density",
        "average",
    ):
        raise ConfigError(f'{where}: \'analyze.score\' must be "density" or "average"')
    if section == "analyze" and "analyzers" in out:
        if not all(isinstance(a, str) for a in out["analyzers"]):
            raise ConfigError(f"{where}: 'analyze.analyzers' must be a list of strings")
    return out


def _validate_table(
    where: str, dotted: str, raw: Dict[str, Any], config: GnostConfig
) -> Dict[str, Any]:
    signals = (
        set(DEFAULT_WEIGHTS) if dotted.endswith("weights") else set(DEFAULT_RANGES)
    )
    out: Dict[str, Any] = {}
    for name, value in raw.items():
        full = f"{dotted}.{name}"
        if name not in signals:
            config.warnings.append(f"{where}: unknown setting '{full}' (ignored)")
        elif dotted.endswith("weights"):
            _check(where, full, value, _NUMBER)
            if not 0 <= value <= 1:
                raise ConfigError(f"{where}: '{full}' must be between 0 and 1")
            out[name] = value
        else:
            if not (
                isinstance(value, list)
                and len(value) == 2
                and all(_is(v, _NUMBER) for v in value)
            ):
                raise ConfigError(
                    f"{where}: '{full}' must be two numbers, e.g. [200, 1000]"
                )
            if value[0] >= value[1]:
                raise ConfigError(
                    f"{where}: '{full}' needs the first number below the second"
                )
            out[name] = value
    return out


def _validate_architecture(
    where: str, out: Dict[str, Any], config: GnostConfig
) -> None:
    """Check `[architecture]`: layers are names, each rule has `from` and `must_not_import`."""
    layers = out.get("layers", [])
    if not all(isinstance(n, str) and n.strip() for n in layers):
        raise ConfigError(
            f"{where}: 'architecture.layers' must be a list of folder names"
        )
    if len(set(layers)) != len(layers):
        raise ConfigError(f"{where}: 'architecture.layers' lists a layer twice")
    known = {"name", "from", "must_not_import", "allow"}
    for index, item in enumerate(out.get("rules", []), start=1):
        label = f"architecture.rules #{index}"
        if not isinstance(item, dict):
            raise ConfigError(
                f"{where}: '{label}' must be a table ([[architecture.rules]])"
            )
        for key in item:
            if key not in known:
                config.warnings.append(
                    f"{where}: unknown setting '{label}.{key}' (ignored)"
                )
        source = item.get("from")
        sources = source if isinstance(source, list) else [source]
        if not source or not all(isinstance(s, str) and s.strip() for s in sources):
            raise ConfigError(
                f"{where}: '{label}' needs 'from' (a path or list of paths)"
            )
        for key in ("must_not_import", "allow"):
            value = item.get(key, [])
            if not isinstance(value, list) or not all(
                isinstance(s, str) for s in value
            ):
                raise ConfigError(f"{where}: '{label}.{key}' must be a list of paths")
        if not item.get("must_not_import"):
            raise ConfigError(
                f"{where}: '{label}' needs 'must_not_import' (a list of paths)"
            )
        if "name" in item and not isinstance(item["name"], str):
            raise ConfigError(f"{where}: '{label}.name' must be text")


def _check(where: str, key: str, value: Any, expected: Any) -> None:
    if not _is(value, expected):
        raise ConfigError(
            f"{where}: '{key}' must be {_type_name(expected)}, got {value!r}"
        )


def report_warnings(config: GnostConfig) -> None:
    for message in config.warnings:
        print(f"gnost: warning: {message}", file=sys.stderr)

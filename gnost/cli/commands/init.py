"""`gnost init`: write a complete `.gnost.toml`, and optionally wire GNOST into the build.

`ConfigTemplate` builds the default settings file from the code's own defaults, and
`InitCommand` writes it and applies the selected integrations from the registry.
"""

from __future__ import annotations

import os
import sys
from typing import Iterable, List, Optional, Sequence

from gnost import __version__
from gnost.cli.commands.onboard import resolve_repo_root
from gnost.config.settings import ANALYZE_MAX_FINDINGS, ANALYZE_TIMEOUT, CONFIG_NAME
from gnost.core.caution import DEFAULT_RANGES, DEFAULT_WEIGHTS, CautionSettings
from gnost.core.risk import RiskSettings
from gnost.reporters.mermaid import DEFAULT_MAX_EDGES
from gnost.utils.integrations import (
    Integration,
    IntegrationError,
    IntegrationResult,
    default_integrations,
)
from gnost.utils.layout import DEFAULT_OUTPUT_DIR
from gnost.vcs.history import HistorySettings


class ConfigTemplate:
    """The text of a `.gnost.toml` with every setting at its default and a comment on each."""

    def render(self) -> str:
        """The whole file."""
        caution, history, risk = CautionSettings(), HistorySettings(), RiskSettings()
        weights = "\n".join(f"{k} = {self._num(v)}" for k, v in DEFAULT_WEIGHTS.items())
        ranges = "\n".join(
            f"{k} = [{self._num(a)}, {self._num(b)}]"
            for k, (a, b) in DEFAULT_RANGES.items()
        )
        authors = ", ".join(f'"{a}"' for a in history.exclude_authors)
        return f"""# GNOST settings for this project. Every line is optional; the values shown are the
# defaults, so you only need to keep what you change. Lines starting with # are examples.
# Precedence: command-line flags, then this file, then the defaults.
# Full guide: https://gnost.readthedocs.io/en/stable/configuration.html

# Files and folders skipped by onboard and analyze. A name matches a folder anywhere;
# a pattern matches file names or paths, for example ["legacy", "*.generated.ts", "docs/build"].
exclude = []

# The folder GNOST writes its files to, inside the project.
output_dir = "{DEFAULT_OUTPUT_DIR}"

# Say so when a newer gnost exists (`gnost --version`; only in a terminal, never in CI).
check_updates = true

# End the Markdown files GNOST writes with a "Generated by GNOST" line.
footer = true

[onboard]
max_edges = {DEFAULT_MAX_EDGES}      # largest diagram drawn file by file; bigger ones are grouped by folder
# collapse = 1       # always group diagrams by folder, this many levels deep
# depth = 3          # limit how deep the execution flow goes
# pages = true       # also publish the explorer for GitHub Pages (docs/ or docs/gnost/), or a folder name

[caution]            # which files are "risky to change"
threshold = {self._num(caution.threshold)}        # lowest caution score reported, 0 to 100
limit = {caution.limit}            # most files reported

[caution.weights]    # the most each signal can add to a score, 0 to 1
{weights}

[caution.ranges]     # [value that counts as 0, value that counts as 1]
{ranges}

[risk]               # files that are fragile to change AND changing often (needs git history)
threshold = {self._num(risk.threshold)}        # lowest risk listed, 0 to 100
limit = {risk.limit}            # most files listed
churn_weight = {self._num(risk.churn_weight)}      # 1 = risk is caution x change activity; 0 = ignore change activity

[history]            # change hotspots: how often files change (needs git and its history)
enabled = {str(history.enabled).lower()}
days = {history.days}           # how far back to look
max_commits = {history.max_commits}     # most commits read
recent_days = {history.recent_days}        # what counts as "recent" in the hotspot table
min_commits = {history.min_commits}         # a file needs this many changes to be listed
top = {history.top}               # most files listed in ONBOARD.md
max_files_per_commit = {history.max_files_per_commit}   # bigger commits (mass reformat, vendoring) are ignored
exclude_authors = [{authors}]   # patterns; bots do not count as people

[architecture]
# Rules about which code may import which. Checked by `onboard` and `gnost changes` (all optional).
# layers = ["api", "service", "db"]   # top to bottom: a layer must not import a layer above it
# fail = false   # `gnost changes` exits with code 3 when a change adds a violation
# [[architecture.rules]]
# name = "the api must not use the database directly"
# from = "src/api/**"                  # files these paths match ...
# must_not_import = ["src/db/**"]      # ... must not import files these paths match
# allow = ["src/db/models/**"]         # exceptions

[analyze]
# analyzers = ["maintainability", "readability"]   # default: all of them
# languages = ["python", "javascript", "typescript", "java"]   # default: all of them
# fail_under = 7.5   # CI: exit with code 3 when the final score (0 to 10) is lower
# score = "average"   # the 0.7.0 formula (average severity) until 0.8.0; default "density"
# badge = true       # write .gnost/badge.svg with the score for the README (or a path)
# baseline = ".gnost/baseline.json"   # report only findings that are not in this file
timeout = {ANALYZE_TIMEOUT}          # seconds each analyzer may run
max_findings = {ANALYZE_MAX_FINDINGS}     # most findings kept per analyzer
parallel = false     # run the analyzers at the same time
"""

    @staticmethod
    def _num(value: float) -> str:
        """A number as TOML text: 40 rather than 40.0."""
        return str(int(value)) if float(value).is_integer() else str(value)


def default_config_text() -> str:
    """The default `.gnost.toml` text (what `gnost init --print` shows)."""
    return ConfigTemplate().render()


class InitCommand:
    """Writes the config file and applies the chosen integrations under one project root."""

    def __init__(
        self,
        root: str,
        integrations: Sequence[Integration],
        force: bool = False,
        dry_run: bool = False,
    ) -> None:
        self.root = root
        self.integrations = integrations
        self.force = force
        self.dry_run = dry_run

    @classmethod
    def available(cls) -> Sequence[Integration]:
        """Every integration `init` offers (the CLI builds its flags from this)."""
        return default_integrations(__version__)

    def run(self) -> int:
        """Do the work and print what happened. Returns the exit code."""
        print(f"GNOST init in {self.root}")
        status = self._write_config()
        try:
            for integration in self.integrations:
                self._report(integration.apply(self.root, self.dry_run, self.force))
        except IntegrationError as exc:
            print(f"gnost: {exc}", file=sys.stderr)
            return 2
        if not self.dry_run and status == 0:
            print("\nNext: gnost onboard .")
        return status

    def _write_config(self) -> int:
        """Write .gnost.toml unless it exists (without force). Returns 1 if it was refused alone."""
        path = os.path.join(self.root, CONFIG_NAME)
        if os.path.exists(path) and not self.force:
            print(
                f"  {CONFIG_NAME}: already exists (use --force to overwrite, --print to see the defaults)"
            )
            return 0 if self.integrations else 1
        if self.dry_run:
            print(f"  {CONFIG_NAME}: would write {path}")
            return 0
        with open(path, "w", encoding="utf-8") as f:
            f.write(default_config_text())
        print(
            f"  {CONFIG_NAME}: written, with every setting at its default; edit what you need"
        )
        return 0

    @staticmethod
    def _report(result: IntegrationResult) -> None:
        """Print one integration's outcome and its diff."""
        messages = {
            "unchanged": "already set up, nothing to do",
            "exists": "already exists (use --force to overwrite)",
            "created": f"written {result.path}",
            "would create": f"would write {result.path}",
            "changed": f"updated {result.path}",
            "would change": f"would change {result.path}",
        }
        print(f"  {result.label}: {messages[result.status]}")
        for line in result.diff:
            print(f"    {line}")
        for note in result.notes:
            print(f"    Note: {note}")


def run(
    path: Optional[str] = None,
    selected: Iterable[str] = (),
    force: bool = False,
    print_only: bool = False,
    dry_run: bool = False,
) -> int:
    """Entry point for `gnost init`: `selected` holds the integration flags that were given."""
    if print_only:
        print(default_config_text(), end="")
        return 0
    wanted = set(selected)
    for integration in InitCommand.available():
        if integration.flag in wanted and integration.requires not in (None, *wanted):
            print(
                f"gnost: --{integration.flag} only works together with --{integration.requires}",
                file=sys.stderr,
            )
            return 2
    chosen: List[Integration] = [
        i
        for i in default_integrations(
            __version__, fork_comments="fork-comments" in wanted
        )
        if i.flag in wanted
    ]
    root = resolve_repo_root(os.path.abspath(path or "."))
    return InitCommand(root, chosen, force=force, dry_run=dry_run).run()

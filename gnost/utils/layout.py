"""Where GNOST writes its files: one folder (`.gnost/` by default) in the project.

`OutputLayout` knows every path inside that folder, the old pre-0.6.0 locations
(`ONBOARD.md`, `docs/...`) that are still read as a fallback, and how to create the folder
with its README and .gitignore. `output_dir` in `.gnost.toml` can name another folder.
"""

from __future__ import annotations

import os
from typing import Optional

DEFAULT_OUTPUT_DIR = ".gnost"
# Old output places, skipped by the scanners so a run never reads its own output.
LEGACY_OUTPUT_PATHS = ("docs/flow", "docs/insights", "docs/analysis")

FOLDER_README = """# GNOST output

This folder was generated by [GNOST](https://gnost.readthedocs.io), a command line tool
that explains a codebase: where it starts, how it flows and which files matter.

| File | What it is |
|---|---|
| `ONBOARD.md` | The onboarding guide: entry points, flow, hotspots, routes, risky files |
| `insights.json` | The same facts as data, for tools and AI (schema: `insights.schema.json`) |
| `flow/` | Mermaid diagrams (`.mmd`) and Markdown pages that GitHub renders |
| `flow.html` | The interactive flow explorer, one page that works offline (not committed) |
| `analysis/` | The code quality report from `gnost analyze -o` (`analysis.json`, `analysis.html`, `analysis.sarif`) |
| `changes/` | The report from `gnost changes BASE`: changed files, blast radius, risk (`changes.md`, `changes.json`) |
| `baseline.json` | Known findings, from `gnost analyze --write-baseline`, so CI can report only new ones |
| `badge.svg` | The final score as a README badge, from `gnost analyze --badge` |

It is safe to commit this folder. The `.html` pages are ignored (see `.gitignore` here)
because they are large and can be rebuilt.

Update it: `npx gnost-cli onboard .` or `gnost onboard .`. Open the explorer: `gnost open flow`.
"""

FOLDER_GITIGNORE = "# Large pages that GNOST rebuilds on demand.\n*.html\n"


class OutputLayout:
    """All output paths for one project root and the old places they replace.

    Create it with the project root and the folder name from the config (default .gnost).
    """

    def __init__(self, root: str, dirname: Optional[str] = None) -> None:
        self.root = os.path.abspath(root)
        self.dirname = dirname or DEFAULT_OUTPUT_DIR
        self.folder = (
            self.dirname
            if os.path.isabs(self.dirname)
            else os.path.join(self.root, self.dirname)
        )
        self.onboard_md = os.path.join(self.folder, "ONBOARD.md")
        self.insights_json = os.path.join(self.folder, "insights.json")
        self.flow_dir = os.path.join(self.folder, "flow")
        self.flow_html = os.path.join(self.folder, "flow.html")
        self.analysis_dir = os.path.join(self.folder, "analysis")
        self.analysis_json = os.path.join(self.analysis_dir, "analysis.json")
        self.analysis_html = os.path.join(self.analysis_dir, "analysis.html")
        self.analysis_sarif = os.path.join(self.analysis_dir, "analysis.sarif")
        self.changes_dir = os.path.join(self.folder, "changes")
        self.changes_md = os.path.join(self.changes_dir, "changes.md")
        self.changes_json = os.path.join(self.changes_dir, "changes.json")
        self.baseline_json = os.path.join(self.folder, "baseline.json")
        self.badge_svg = os.path.join(self.folder, "badge.svg")

    # The places GNOST wrote to before 0.6.0.
    @property
    def legacy_onboard_md(self) -> str:
        """The old ONBOARD.md at the project root."""
        return os.path.join(self.root, "ONBOARD.md")

    @property
    def legacy_flow_dir(self) -> str:
        """The old docs/flow folder."""
        return os.path.join(self.root, "docs", "flow")

    @property
    def legacy_analysis_html(self) -> str:
        """The old docs/analysis/gnost_analysis.html report."""
        return os.path.join(self.root, "docs", "analysis", "gnost_analysis.html")

    @property
    def relative_name(self) -> str:
        """The folder as shown in messages and README links (forward slashes)."""
        return self.dirname.replace(os.sep, "/")

    def has_legacy_output(self) -> bool:
        """True if GNOST output from before 0.6.0 is present."""
        return os.path.isfile(self.legacy_onboard_md) or os.path.isdir(
            self.legacy_flow_dir
        )

    def prepare(self) -> None:
        """Create the folder with its README and .gitignore (an existing .gitignore is kept)."""
        os.makedirs(self.folder, exist_ok=True)
        with open(os.path.join(self.folder, "README.md"), "w", encoding="utf-8") as f:
            f.write(FOLDER_README)
        ignore = os.path.join(self.folder, ".gitignore")
        if not os.path.exists(ignore):
            with open(ignore, "w", encoding="utf-8") as f:
                f.write(FOLDER_GITIGNORE)

    def moved_notice(self) -> str:
        """One message about the 0.6.0 move, shown while old output is still being used."""
        return (
            f"GNOST now writes to {self.relative_name}/ (before 0.6.0: ONBOARD.md and docs/). "
            "Your old files were left where they are; run `gnost onboard .` to create the "
            "new folder, then delete the old files when you like."
        )

"""Blocks that GNOST keeps up to date inside a project's README.md.

Each block sits between its own marker comments, so re-running replaces it instead of adding
a copy. `ReadmeInjector` writes the onboarding link (`onboard --inject`); `MindMapInjector`
writes the project map (`onboard --inject-mindmap`).
"""

from __future__ import annotations

import re
from pathlib import Path

GNOST_START = "<!-- GNOST:ONBOARDING:START -->"
GNOST_END = "<!-- GNOST:ONBOARDING:END -->"

MINDMAP_START = "<!-- GNOST:MINDMAP:START -->"
MINDMAP_END = "<!-- GNOST:MINDMAP:END -->"

DEFAULT_LINK = "./.gnost/ONBOARD.md"


def render_block(link: str = DEFAULT_LINK) -> str:
    """The onboarding block: a badge that links to the guide."""
    return f"""{GNOST_START}

## Onboarding
This repository includes an **auto-generated onboarding guide**

[![Onboarding](https://img.shields.io/badge/onboarding-ONBOARD.md-cyan)]({link})

Generated by <a href="https://gnost.readthedocs.io">GNOST</a> to help understand the codebase.

{GNOST_END}
"""


class ReadmeInjector:
    """Injects or updates one GNOST-managed block in README.md.

    A new block goes before the first `##` heading; subclasses choose other markers,
    content and placement.
    """

    START = GNOST_START
    END = GNOST_END

    def __init__(self, root: str, link: str = DEFAULT_LINK) -> None:
        self.readme_path = Path(root) / "README.md"
        self.block = render_block(link)

    def inject(self) -> bool:
        """Insert the block, or replace the one already there.

        Returns False (and writes nothing) when there is no README.md.
        """
        if not self.readme_path.exists():
            return False
        content = self.readme_path.read_text(encoding="utf-8")
        if self.START in content and self.END in content:
            updated = self._update_block(content)
        else:
            updated = self._insert(content)
        self.readme_path.write_text(updated, encoding="utf-8")
        return True

    def _update_block(self, content: str) -> str:
        return re.sub(
            rf"{re.escape(self.START)}.*?{re.escape(self.END)}\n?",
            lambda _match: self.block,
            content,
            flags=re.DOTALL,
        )

    def _insert(self, content: str) -> str:
        """Insert the block before the first H2 (##) heading, or append it."""
        lines = content.splitlines()
        for i, line in enumerate(lines):
            if line.startswith("## ") and not line.startswith("###"):
                return "\n".join(lines[:i] + [""] + [self.block] + [""] + lines[i:])
        return content.rstrip() + "\n\n" + self.block + "\n"


class MindMapInjector(ReadmeInjector):
    """Keeps the project map (an SVG image or a Mermaid block) at the end of README.md.

    `image` is the SVG path relative to the README; `mermaid` is Mermaid source used instead.
    """

    START = MINDMAP_START
    END = MINDMAP_END

    def __init__(self, root: str, image: str = "", mermaid: str = "") -> None:
        self.readme_path = Path(root) / "README.md"
        self.block = self.render(image, mermaid)

    @classmethod
    def render(cls, image: str = "", mermaid: str = "") -> str:
        """The block: a heading, then the image or the Mermaid diagram, then a credit line."""
        if mermaid:
            body = f"```mermaid\n{mermaid.rstrip()}\n```"
        else:
            body = f"![Project map: folders as branches, files as leaves]({image})"
        return (
            f"{cls.START}\n\n## Project map\n\n{body}\n\n"
            'Generated by <a href="https://gnost.readthedocs.io">GNOST</a> '
            "(`gnost onboard . --inject-mindmap`).\n\n"
            f"{cls.END}\n"
        )

    def _insert(self, content: str) -> str:
        """The map goes at the end of the README."""
        return content.rstrip() + "\n\n" + self.block
